function Button({
  className,
  variant = "default",
  size = "default",
  asChild = false,
  loading = false,
  disabled,
  children,
  ...props
}: React.ComponentProps<"button"> &
  VariantProps<typeof buttonVariants> & {
    asChild?: boolean
    /**
     * Shows a spinner and blocks interaction. Children still render, so callers
     * that already swap their own label (`loading ? "Saving…" : "Save"`) keep
     * working unchanged.
     */
    loading?: boolean
  }) {
  const shared = {
    "data-slot": "button",
    "data-variant": variant,
    "data-size": size,
    "data-loading": loading || undefined,
    "aria-busy": loading || undefined,
    className: cn(buttonVariants({ variant, size, className })),
  }

  // Slot.Root requires exactly one child, and even a falsy expression counts
  // towards that total — so the spinner slot must not exist at all here.
  if (asChild) {
    return (
      <Slot.Root {...shared} {...props}>
        {children}
      </Slot.Root>
    )
  }

  return (
    <button {...shared} disabled={disabled || loading} {...props}>
      {loading && <Loader2 className="animate-spin" aria-hidden />}
      {children}
    </button>
  )
}

export { Button, buttonVariants }
